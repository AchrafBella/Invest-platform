"""simple bot"""

import logging
import math
import os
from dataclasses import dataclass

from bots.tools import fetch_data

DATABASE_DIR = "database"
DB_FILE = os.path.join(DATABASE_DIR, "tradingplatform.db")

logger = logging.getLogger(__name__)

BUY_SIGNAL = "BUY"
SELL_SIGNAL = "SELL"


@dataclass
class TradeSignal:
    """
    Represents a trading decision generated by the bot.

    Attributes:
        ticker (str): Stock symbol.
        signal (str): Either "BUY" or "SELL".
        price (float | None): Latest observed market price (may be None if unavailable).
        pct_change (float): Percentage price change over the evaluation period.
    """

    ticker: str
    signal: str
    price: float | None
    pct_change: float


class TradingBot:
    def __init__(
        self,
        bot_name: str,
        stocks_watch_list: list[str],
        pct_change_period: int = 5,
        threshold_buy: float = -0.30,
        threshold_sell: float = 0.30,
    ):
        """
        Initialize the trading bot with configuration parameters.

        Args:
            bot_name (str): Name identifier for the bot.
            stocks_watch_list (list[str]): List of tickers to monitor.
            threshold_buy (float): Fractional drop threshold triggering a buy signal.
            threshold_sell (float): Fractional rise threshold triggering a sell signal.
            pct_change_period (int): Number of periods used to compute percentage change.
        """

        if pct_change_period <= 0:
            raise ValueError("pct_change_period must be greater than zero")
        if threshold_buy >= 0:
            raise ValueError("threshold_buy must be negative")
        if threshold_sell <= 0:
            raise ValueError("threshold_sell must be positive")

        self.stocks_watch_list = stocks_watch_list
        self.bot_name = bot_name
        self.pct_change_period = pct_change_period
        self.threshold_buy = threshold_buy
        self.threshold_sell = threshold_sell

    def signal(self) -> list[TradeSignal]:
        """
        Generate trading signals based on market data analysis.

        For each watched ticker, the bot:
        - Fetches daily historical data.
        - Computes percentage change over a rolling period.
        - Applies buy/sell thresholds.
        - Fetches intraday price when a signal is triggered.

        Returns:
            list[TradeSignal]: List of generated trade signals (BUY or SELL).
        """
        signal_list = []

        for ticker in self.stocks_watch_list:
            logger.info("Checking %s for buy/sell signal", ticker)

            try:
                df = fetch_data(ticker, interval="1d", period="10d")
                if df.empty:
                    logger.warning("No daily data returned for %s", ticker)
                    continue

                pct_change_fraction = float(
                    df[("Close", ticker)]
                    .pct_change(periods=self.pct_change_period)
                    .iloc[-1]
                )
                if not math.isfinite(pct_change_fraction):
                    logger.warning("Insufficient daily data to evaluate %s", ticker)
                    continue

                close_price = float(df[("Close", ticker)].iloc[-1])
                pct_change_close = pct_change_fraction * 100
                logger.info(
                    "ticker %s with close price %s & volatility %s",
                    ticker,
                    close_price,
                    pct_change_close,
                )

                if pct_change_fraction <= self.threshold_buy:

                    df_min = fetch_data(ticker, interval="1m", period="1d")
                    intraday_price = (
                        float(df_min.iloc[-1][("Close", ticker)])
                        if not df_min.empty
                        else None
                    )
                    signal_list.append(
                        TradeSignal(
                            ticker=ticker,
                            signal=BUY_SIGNAL,
                            price=intraday_price,
                            pct_change=pct_change_close,
                        )
                    )

                elif pct_change_fraction >= self.threshold_sell:

                    df_min = fetch_data(ticker, interval="1m", period="1d")
                    intraday_price = (
                        float(df_min.iloc[-1][("Close", ticker)])
                        if not df_min.empty
                        else None
                    )
                    signal_list.append(
                        TradeSignal(
                            ticker=ticker,
                            signal=SELL_SIGNAL,
                            price=intraday_price,
                            pct_change=pct_change_close,
                        )
                    )

            except Exception:
                logger.exception("Error fetching data for %s", ticker)
                continue

        return signal_list
